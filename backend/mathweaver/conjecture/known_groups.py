# ---------------------------------------------------------------------------
# Convenience: orders for which at least one known group exists
# ---------------------------------------------------------------------------

def known_orders() -> set[int]:
    """Return the set of orders for which at least one known group exists."""
    return {len(table) for table in KNOWN_GROUPS.values()}


def groups_of_order(order: int) -> list[tuple[str, list[list[int]]]]:
    """Return all known groups of the given order.

    Returns an empty list if no known group has that order — callers
    should treat this as "undecidable" rather than "confirmed".
    """
    return [
        (name, table)
        for name, table in KNOWN_GROUPS.items()
        if len(table) == order
    ]
