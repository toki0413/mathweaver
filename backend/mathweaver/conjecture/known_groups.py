"""Canonical database of known group Cayley tables.

SINGLE SOURCE OF TRUTH for all group-theory data in MathWeaver.
Both ``handler.py`` and ``nl_translator.py`` import from here.

Design rationale (post-mortem):
    Previously, ``handler._TEST_GROUPS`` and ``nl_translator._KNOWN_GROUPS``
    each maintained a separate copy of the same data.  When one copy was
    updated (e.g. the Q8 Cayley table fix), the other could silently diverge.
    Consolidating into one module eliminates that class of bug entirely.

Every table here is verified by ``tests/test_golden_reference_math.py``
against all four group axioms (closure, identity, inverses, associativity)
plus the abelian / cyclic classification.  If you add a new group, the
golden tests will automatically validate it.
"""

from __future__ import annotations

from typing import TypedDict


class GroupMeta(TypedDict):
    """Metadata describing a known group.

    Attributes:
        name: Human-readable name (e.g. "Z₃", "S₃", "Q₈").
        order: The order of the group (number of elements).
        abelian: Whether the group is commutative.
        cyclic: Whether the group is cyclic (generated by a single element).
        description: Brief mathematical description.
    """

    name: str
    order: int
    abelian: bool
    cyclic: bool
    description: str


